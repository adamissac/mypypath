/* Python for Data — end-of-unit test question pools.
 *
 * Foundations keeps its pools as hand-written JSON under
 * assets/data/unit-tests/. This course keeps them here and generates the JSON,
 * for the same reason the lessons are generated: the questions have to stay
 * pinned to the lessons they test, and a second hand-maintained copy drifts.
 *
 * Each unit offers a pool; the paper draws ten from it, so the pool is
 * deliberately larger than ten to give a retake different questions.
 *
 * ids are u<unit>d-m<nn> — the d marks the course, so a Data id can never
 * collide with a Foundations one in a teacher's saved quiz.
 */

const mcq = (unit, items) => items.map((q, i) => ({
  id: `u${unit}d-m${String(i + 1).padStart(2, '0')}`,
  prompt: q[0],
  choices: q[1],
  answer: q[2],
  explain: q[3],
  kind: 'mcq',
}));


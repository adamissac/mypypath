/* What a unit overview page says about each lesson, and the page region itself.
 *
 * Pure: takes HTML strings and data, returns strings. scripts/build-unit-pages.mjs
 * does the file I/O. The region keeps the hooks other scripts rely on:
 * .unit-trail (lesson-progress.js ticks lessons off), [data-unit-progress]
 * (unit-progress-panel.js), [data-unit-test-status] / [data-unit-test-link]
 * (lesson-progress.js fills the test line). */
import * as cheerio from 'cheerio';

const esc = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const clean = (s) => String(s || '').replace(/\s+/g, ' ').trim();

const SUMMARY_MAX = 90;

/* Lower-case the first word of a later topic so the list reads as one
   sentence -- unless it is a name or an acronym (Python, Excel, JSON, HTTP). */
const PROPER = new Set(['Python', 'Excel', 'Matplotlib', 'Windows', 'Mac', 'Linux', 'Git', 'GitHub', 'IDLE', 'VS']);
function lower(label) {
  const word = label.split(/[\s(]/)[0].replace(/['’]s$/, '');
  if (PROPER.has(word) || !/^[A-Z][a-z]/.test(word)) return label;
  return label.charAt(0).toLowerCase() + label.slice(1);
}

export function lessonSummary(html, course) {
  const $ = cheerio.load(html);
  if (course === 'data') {
    const d = clean($('meta[name="description"]').attr('content'));
    if (d) return d;
  }
  const learn = $('h2').filter((_, el) => /What You Will Learn/i.test($(el).text())).first();
  if (learn.length) {
    const labels = learn.nextAll('ul').first().find('li').map((_, li) => {
      const strong = $(li).find('strong').first();
      return clean(strong.length ? strong.text() : $(li).text()).replace(/:$/, '');
    }).get().filter(Boolean);
    let out = '';
    labels.forEach((label, i) => {
      const next = i === 0 ? label : `${out}, ${lower(label)}`;
      if (i === 0 || next.length <= SUMMARY_MAX) out = next;
    });
    if (out) return out;
  }
  const overview = $('h2').filter((_, el) => /Overview/i.test($(el).text())).first();
  let p = overview.length ? overview.nextAll('p').first() : $();
  if (overview.length && !p.length) p = overview.parent().nextAll('p').first();
  if (!p.length) p = $('main p').first();
  const para = clean(p.text());
  const sentence = para.match(/^.*?[.!?](\s|$)/);
  return clean(sentence ? sentence[0] : para).slice(0, 140);
}

export function lessonTitle(html, course, fallback) {
  if (course === 'data') return clean(fallback);
  const $ = cheerio.load(html);
  const raw = clean($('title').first().text());
  const t = raw.replace(/^Unit\s+\d+\s*•\s*/, '').replace(/\s*•\s*PyPath\s*$/, '');
  return t || clean(fallback);
}

export function lessonMinutes(html, { editors = 0, exercises = 0 } = {}) {
  const $ = cheerio.load(html);
  const scope = $('.lesson-content').length ? $('.lesson-content') : $('main');
  scope.find('pre, code, script, style, textarea, nav, aside').remove();
  const words = clean(scope.text()).split(' ').filter(Boolean).length;
  const minutes = words / 200 + 2 * editors + 3 * exercises;
  return Math.max(5, Math.round(minutes / 5) * 5);
}

/* The lesson's own estimate (every lesson's overview carries one as a pill,
   e.g. "20–25 min"), so the unit page never contradicts the lesson. Estimated
   from its length only when a lesson has none. */
export function lessonTime(html, counts) {
  const $ = cheerio.load(html);
  const pill = $('.lesson-meta .pill, .pill').filter((_, el) => /\bmin\b/.test($(el).text())).first();
  if (pill.length) return clean(pill.text());
  return `About ${lessonMinutes(html, counts)} min`;
}

